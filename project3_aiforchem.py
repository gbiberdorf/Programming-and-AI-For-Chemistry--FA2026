def get_uniprot_sequences(accessions, batch_size=100):

    sequences = {}

    total_batches = int(np.ceil(len(accessions) / batch_size))

    for start in range(0, len(accessions), batch_size):

        batch = accessions[start:start + batch_size]

        query = " OR ".join(
            [f"accession:{acc}" for acc in batch]
        )

        url = "https://rest.uniprot.org/uniprotkb/stream"

        params = {
            "query": query,
            "format": "fasta"
        }

        try:

            response = requests.get(
                url,
                params=params,
                timeout=60
            )

            response.raise_for_status()

            current_accession = None
            current_sequence = []

            for line in response.text.splitlines():

                if line.startswith(">"):

                    if current_accession is not None:
                        sequences[current_accession] = "".join(
                            current_sequence
                        )

                    header = line[1:].split()[0]

                    if "|" in header:
                        current_accession = header.split("|")[1]
                    else:
                        current_accession = header

                    current_sequence = []

                else:
                    current_sequence.append(line.strip())

            if current_accession is not None:
                sequences[current_accession] = "".join(
                    current_sequence
                )

            print(
                f"Retrieved batch {start // batch_size + 1} "
                f"of {total_batches}"
            )

        except requests.exceptions.RequestException as e:

            print("Error retrieving batch:", e)

        time.sleep(0.2)

    return sequences


