class ProteinCNN_Attention(nn.Module):
    def __init__(self, filters, kernel_size, dropout):
        super().__init__()

        self.conv1 = nn.Conv1d(20, filters, kernel_size=kernel_size, padding="same")
        self.conv2 = nn.Conv1d(filters, filters * 2, kernel_size=kernel_size, padding="same")

        self.position_embedding = nn.Embedding(X_train.shape[2], filters * 2)

        #self-attention
        self.attention = nn.MultiheadAttention(
            embed_dim=filters * 2,
            num_heads=4,
            dropout=dropout,
            batch_first=True
        )

        self.dropout = nn.Dropout(dropout)

        self.fc1 = nn.Linear(filters * 4, 32)
        self.fc2 = nn.Linear(32, 1)

    def forward(self, x):
        padding_mask = (x.abs().sum(dim=1) == 0)

        #convolutional layers
        x = torch.relu(self.conv1(x))
        x = torch.relu(self.conv2(x))
        x = x.transpose(1, 2)

        #positional info
        positions = torch.arange(x.shape[1], device=x.device).unsqueeze(0)

        x = x + self.position_embedding(positions)

        attention_output, attention_weights = self.attention(
            x, x, x,
            key_padding_mask=padding_mask,
            need_weights=False
        )

        x = x + attention_output
        valid_mask = (~padding_mask).unsqueeze(-1)

        x_average = (
            (x * valid_mask).sum(dim=1) /
            valid_mask.sum(dim=1).clamp(min=1)
        )

        x_max = x.masked_fill(
            padding_mask.unsqueeze(-1), -1e9
        ).max(dim=1).values

        #average and max pooling
        x = torch.cat([x_average, x_max], dim=1)

        x = self.dropout(x)
        x = torch.relu(self.fc1(x))
        x = self.dropout(x)

        return self.fc2(x).squeeze(1)


