class ProteinCNN(nn.Module):

    def __init__(self, filters=32, kernel_size=5, dropout=0.5):

        super(ProteinCNN, self).__init__()

        self.conv1 = nn.Conv1d(
            in_channels=20,
            out_channels=filters,
            kernel_size=kernel_size,
            padding=kernel_size // 2
        )

        self.conv2 = nn.Conv1d(
            in_channels=filters,
            out_channels=filters * 2,
            kernel_size=kernel_size,
            padding=kernel_size // 2
        )

        self.pool = nn.MaxPool1d(2)

        self.adaptive_pool = nn.AdaptiveMaxPool1d(1)

        self.dropout = nn.Dropout(dropout)

        self.fc = nn.Linear(filters * 2, 1)

    def forward(self, x):

        x = torch.relu(self.conv1(x))
        x = self.pool(x)

        x = torch.relu(self.conv2(x))
        x = self.pool(x)

        x = self.adaptive_pool(x)
        x = x.flatten(start_dim=1)

        x = self.dropout(x)

        x = self.fc(x)

        return x

def train_epoch(model, train_loader, criterion, optimizer):

    model.train()

    total_loss = 0
    gradient_norms = []

    for X_batch, y_batch in train_loader:

        X_batch = X_batch.to(device)
        y_batch = y_batch.to(device)

        optimizer.zero_grad()

        outputs = model(X_batch).reshape(-1)

        loss = criterion(outputs, y_batch)

        loss.backward()
        grad_norm = torch.nn.utils.clip_grad_norm_(
            model.parameters(),
            max_norm=5
        )

        gradient_norms.append(grad_norm.item())

        optimizer.step()

        total_loss += loss.item() * X_batch.size(0)

    average_loss = total_loss / len(train_loader.dataset)

    mean_gradient_norm = np.mean(gradient_norms)

    return average_loss, mean_gradient_norm

def evaluate(model, data_loader, criterion):

    model.eval()

    total_loss = 0

    all_labels = []
    all_predictions = []
    all_probabilities = []

    with torch.no_grad():

        for X_batch, y_batch in data_loader:

            X_batch = X_batch.to(device)
            y_batch = y_batch.to(device)

            outputs = model(X_batch).reshape(-1)

            loss = criterion(outputs, y_batch)

            probabilities = torch.sigmoid(outputs)

            predictions = (probabilities >= 0.5).float()

            total_loss += loss.item() * X_batch.size(0)

            all_labels.extend(y_batch.cpu().numpy())
            all_predictions.extend(predictions.cpu().numpy())
            all_probabilities.extend(probabilities.cpu().numpy())

    average_loss = total_loss / len(data_loader.dataset)
    accuracy = accuracy_score(all_labels, all_predictions)

    return (average_loss, accuracy, np.array(all_labels), np.array(all_predictions), np.array(all_probabilities))


