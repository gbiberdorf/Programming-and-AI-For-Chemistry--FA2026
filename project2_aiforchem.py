class FCNN(nn.Module):
    def __init__(self, input_size, hidden_size, dropout):
        super().__init__()

        self.network = nn.Sequential(nn.Linear(input_size, hidden_size), nn.ReLU(), nn.Dropout(dropout), nn.Linear(hidden_size, hidden_size // 2), nn.ReLU(), nn.Dropout(dropout), nn.Linear(hidden_size // 2, 1))

    def forward(self, x):
        return self.network(x).squeeze(1)


#train functions
def train_epoch(model, loader, optimizer, loss_function):
    model.train()
    total_loss = 0
    gradient_norms = [] #track gradient norms

    for batch_X, batch_y in loader:
        batch_X, batch_y = batch_X.to(device), batch_y.to(device)

        optimizer.zero_grad()
        output = model(batch_X)
        loss = loss_function(output, batch_y)
        loss.backward()
#raw norms to make sure gradients don't disappear
        grad_norm = torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
        gradient_norms.append(float(grad_norm))

        optimizer.step()
        total_loss += loss.item() * len(batch_y)

    return total_loss / len(loader.dataset), np.mean(gradient_norms)


def evaluate(model, loader, loss_function):
    model.eval()
    total_loss = 0
    labels, probabilities = [], []

    with torch.no_grad():
        for batch_X, batch_y in loader:
            batch_X, batch_y = batch_X.to(device), batch_y.to(device)
            output = model(batch_X)
            loss = loss_function(output, batch_y)

            total_loss += loss.item() * len(batch_y)
            labels.extend(batch_y.cpu().numpy())
            probabilities.extend(torch.sigmoid(output).cpu().numpy())

    labels = np.array(labels).astype(int)
    probabilities = np.array(probabilities)
    predictions = (probabilities >= 0.5).astype(int)

    return (total_loss / len(loader.dataset), accuracy_score(labels, predictions), labels, predictions, probabilities)


