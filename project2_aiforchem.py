#protein sequences from uniprot
def get_uniprot_sequences(accessions, batch_size=100):
    sequences = {}
    total = len(accessions)

    for start in range(0, total, batch_size):
        batch = accessions[start:start + batch_size]

        query = " OR ".join([f"accession:{acc}" for acc in batch])
        url = "https://rest.uniprot.org/uniprotkb/search"
        params = {"query": query, "format": "fasta", "size": batch_size}

        try:
            response = requests.get(url, params=params, timeout=60)
            response.raise_for_status()
        except requests.RequestException as e:
            print("request failed:", e)
            continue

        lines = response.text.strip().splitlines()
        current_accession = None
        current_sequence = []

        for line in lines:
            if line.startswith(">"):
                if current_accession is not None:
                    sequences[current_accession] = "".join(current_sequence)

                parts = line.split("|")
                current_accession = (parts[1] if len(parts) >= 2 else None)
                current_sequence = []

            else:
                current_sequence.append(line.strip())

        if current_accession is not None:
            sequences[current_accession] = "".join(current_sequence)

    return sequences


